const CATEGORY_ORDER = ["Experience", "Products", "Platform", "Trust", "Services", "Site", "Developer"];

// Keep every category together while preserving the original order of chapters
// within that category. The hero remains first and Contact remains last.
const CHAPTERS = [...CHAPTER_DATA]
  .sort((a, b) => {
    const rank = (chapter) => {
      if (chapter.key === "hero") return -1;
      if (chapter.key === "contact") return CATEGORY_ORDER.length + 1;
      const categoryIndex = CATEGORY_ORDER.indexOf(chapter.cat);
      return categoryIndex === -1 ? CATEGORY_ORDER.length : categoryIndex;
    };

    return rank(a) - rank(b);
  })
  .map((chapter, index) => ({
    ...chapter,
    num: String(index + 1).padStart(2, "0")
  }));

const CATEGORIES = [...new Set(CHAPTERS.filter((c) => c.key === "ch").map((c) => c.cat))];
